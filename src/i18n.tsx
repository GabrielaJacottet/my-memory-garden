const MESSAGES: Record<Language, Messages> = { pt, en, es }

function storedLanguage(): Language {
  try {
    const value = localStorage.getItem(STORAGE_KEY)
    return LANGUAGES.some(({ id }) => id === value) ? value as Language : DEFAULT_LANGUAGE
  } catch {
    return DEFAULT_LANGUAGE
  }
}

interface I18n {
  language: Language
  locale: string
  t: Messages
  setLanguage(language: Language): void
}

const I18nContext = createContext<I18n | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState(storedLanguage)
  const locale = LANGUAGES.find(({ id }) => id === language)!.locale

  useEffect(() => {
    document.documentElement.lang = locale
    try { localStorage.setItem(STORAGE_KEY, language) } catch { /* the choice just won't be remembered */ }
  }, [language, locale])

  return <I18nContext.Provider value={{ language, locale, t: MESSAGES[language], setLanguage }}>{children}</I18nContext.Provider>
}

export function useI18n(): I18n {
  const context = useContext(I18nContext)
  if (!context) throw new Error('useI18n must be used inside <LanguageProvider>')
  return context
}

export function LanguageSwitcher({ className = '' }: { className?: string }) {
  const { language, setLanguage, t } = useI18n()
  return (
    <div className={`language-switcher ${className}`.trim()} role="group" aria-label={t.language}>
      {LANGUAGES.map(({ id, short, name, locale }) => (
        <button key={id} type="button" lang={locale} title={name} aria-label={name} aria-pressed={language === id} onClick={() => setLanguage(id)}>{short}</button>
      ))}
    </div>
  )
}
